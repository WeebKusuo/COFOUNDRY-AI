import { useState } from 'react';
import { Link, useParams } from 'react-router';
import { ArrowLeft, Lock, Mic, ShieldCheck } from 'lucide-react';
import {
  CONFIDENTIALITY_NOTICE,
  INTERVIEW_PRIVACY_NOTICE,
  PROVIDER_RETENTION_NOTICE,
  type InterviewConsentItem,
  type InterviewSessionView,
} from '@cofoundry/shared';
import {
  Alert,
  Badge,
  Button,
  ButtonLink,
  Card,
  CardHeader,
  CheckboxField,
  QueryState,
  TextAreaField,
} from '../../components/ui';
import { ApiError } from '../../lib/api/client';
import { BriefPreviewCard } from '../briefs/BriefPreviewCard';
import { formatDate } from '../briefs/status';
import { useInterview, useInterviewActions } from './api';
import { ReportSection } from './ReportView';
import { CorrectionControl } from '../safety/CorrectionControl';
import { BlockControl, ReportControl } from '../safety/SafetyActions';
import { EvaluationBadge, InterviewStatusBadge } from './status';

const CONSENT_TEXT: Record<InterviewConsentItem, { label: string; hint: string }> = {
  assessment: {
    label: 'I agree to take this AI-assisted assessment and share the results with this founder.',
    hint: 'Your answers, code and the report are shared only with the founder who invited you. Required.',
  },
  external_ai_processing: {
    label:
      'I agree that my resume text, answers and code are processed by the AI provider listed below.',
    hint: 'Questions and evaluations are generated by an external AI service. Required.',
  },
  speech_transcription: {
    label: 'I want to answer by voice (speech is transcribed by our own speech service).',
    hint: 'Optional. Recordings are deleted right after transcription. Without this you type every answer, with no penalty.',
  },
};

function errorMessage(err: unknown): string | null {
  return err instanceof ApiError ? err.message : err ? 'Something went wrong. Try again.' : null;
}

function AcceptForm({ view }: { view: InterviewSessionView }) {
  const actions = useInterviewActions(view.id);
  const [items, setItems] = useState<Record<InterviewConsentItem, boolean>>({
    assessment: false,
    external_ai_processing: false,
    speech_transcription: false,
  });
  const [declining, setDeclining] = useState(false);
  const [reason, setReason] = useState('');
  const ready = items.assessment && items.external_ai_processing;
  const providers = view.readiness?.interviewer.providers ?? [];
  return (
    <Card as="section" aria-labelledby="accept-heading">
      <CardHeader
        title={<span id="accept-heading">Accept the interview</span>}
        description="About 40 minutes: a spoken conversation about your resume and experience, then a short coding task."
      />
      <div className="flex flex-col gap-4">
        {(Object.keys(CONSENT_TEXT) as InterviewConsentItem[]).map((k) => (
          <CheckboxField
            key={k}
            label={CONSENT_TEXT[k].label}
            hint={CONSENT_TEXT[k].hint}
            checked={items[k]}
            onChange={(e) => setItems((s) => ({ ...s, [k]: e.target.checked }))}
          />
        ))}
        <div className="rounded-lg bg-surface-sunk p-4 text-sm text-ink-muted">
          <p className="font-medium text-ink">AI provider</p>
          <p>{providers.length ? providers.join(', ') : 'No AI provider is configured.'}</p>
          <p className="mt-2">{PROVIDER_RETENTION_NOTICE}</p>
          <p className="mt-2">{INTERVIEW_PRIVACY_NOTICE}</p>
          <p className="mt-2">
            Your camera is optional and shown only to you: it is never recorded or analysed. The
            current version of your profile (revision {view.currentProfileRevision ?? '—'}) is
            shared with the founder when you accept.
          </p>
        </div>
        {view.readiness && !view.readiness.interviewer.available ? (
          <Alert tone="caution" title="Interview unavailable">
            {view.readiness.interviewer.message}
          </Alert>
        ) : null}
        {actions.accept.error ? (
          <Alert tone="danger" title="Could not accept" live>
            {errorMessage(actions.accept.error)}
          </Alert>
        ) : null}
        <div className="flex flex-wrap gap-3">
          <Button
            disabled={!ready || view.currentProfileRevision === null}
            loading={actions.accept.isPending}
            onClick={() =>
              actions.accept.mutate({
                briefVersion: view.briefVersion,
                profileRevision: view.currentProfileRevision!,
                items,
              })
            }
          >
            Accept invitation
          </Button>
          <Button variant="ghost" onClick={() => setDeclining((d) => !d)}>
            Decline
          </Button>
        </div>
        {declining ? (
          <div className="flex flex-col gap-3">
            <TextAreaField
              label="Reason (optional, shared with the founder)"
              maxLength={500}
              value={reason}
              onChange={(e) => setReason(e.target.value)}
            />
            <Button
              variant="danger"
              className="self-start"
              loading={actions.decline.isPending}
              onClick={() => actions.decline.mutate(reason)}
            >
              Decline invitation
            </Button>
          </div>
        ) : null}
      </div>
    </Card>
  );
}

function Body({ view }: { view: InterviewSessionView }) {
  const actions = useInterviewActions(view.id);
  const can = (a: string) => view.allowedActions.includes(a as never);
  return (
    <div className="flex flex-col gap-6">
      <div className="flex flex-col gap-2">
        <Link
          to="/candidate/inbox"
          className="flex items-center gap-1 text-sm text-ink-muted hover:underline"
        >
          <ArrowLeft className="size-4" aria-hidden="true" /> Inbox
        </Link>
        <h1 className="text-2xl font-bold text-ink sm:text-3xl">{view.brief.title}</h1>
        <div className="flex flex-wrap items-center gap-2 text-sm text-ink-muted">
          <InterviewStatusBadge status={view.status} />
          <EvaluationBadge status={view.evaluationStatus} />
          <span>From {view.founder.displayName}</span>
          {view.status === 'invited' ? <span>· expires {formatDate(view.expiresAt)}</span> : null}
        </div>
      </div>

      {view.status === 'cancelled' ? (
        <Alert tone="caution" title="This interview was cancelled">
          {view.cancellationReason === 'brief_closed'
            ? 'The founder closed the brief.'
            : view.cancellationReason === 'consent_withdrawn'
              ? 'You withdrew your consent.'
              : view.cancellationReason === 'unavailable'
                ? 'This collaboration is no longer available.'
                : 'The interview was cancelled before it was submitted.'}
        </Alert>
      ) : null}
      {view.status === 'expired' ? (
        <Alert tone="caution" title="This invitation expired">
          Invitations can be accepted and started within 7 days.
        </Alert>
      ) : null}

      {can('acknowledge_brief') ? (
        <Card as="section" aria-labelledby="ack-heading">
          <CardHeader
            title={<span id="ack-heading">Read the full brief</span>}
            description="The full brief includes the founder’s confidential problem and solution."
          />
          <p className="text-sm text-ink-muted">{CONFIDENTIALITY_NOTICE}</p>
          <Button
            className="mt-4"
            icon={<Lock className="size-4" aria-hidden="true" />}
            loading={actions.acknowledge.isPending}
            onClick={() => actions.acknowledge.mutate()}
          >
            I acknowledge — show the full brief
          </Button>
        </Card>
      ) : null}

      {view.fullBrief ? (
        <Card as="section" aria-labelledby="full-heading">
          <CardHeader
            title={<span id="full-heading">Problem and solution</span>}
            description="Confidential."
          />
          <div className="flex flex-col gap-3 text-ink">
            <p className="whitespace-pre-line">{view.fullBrief.problem}</p>
            <p className="whitespace-pre-line">{view.fullBrief.solution}</p>
          </div>
        </Card>
      ) : null}

      {can('accept') ? <AcceptForm view={view} /> : null}

      {view.status === 'accepted' || view.status === 'in_progress' || view.status === 'coding' ? (
        <Card as="section" className="flex flex-wrap items-center justify-between gap-4">
          <div>
            <h2 className="flex items-center gap-2 text-lg font-semibold text-ink">
              <Mic className="size-5 text-ink" aria-hidden="true" />
              {view.status === 'accepted' ? 'Ready when you are' : 'Your interview is in progress'}
            </h2>
            <p className="text-sm text-ink-muted">
              {view.status === 'accepted'
                ? 'Check your microphone, audio and resume before you start. The timer starts when you press Start.'
                : 'Continue where you left off. The timer kept running while you were away.'}
            </p>
          </div>
          <ButtonLink
            to={
              view.status === 'accepted'
                ? `/candidate/interviews/${view.id}/prepare`
                : `/candidate/interviews/${view.id}/room`
            }
          >
            {view.status === 'accepted' ? 'Prepare and start' : 'Continue interview'}
          </ButtonLink>
        </Card>
      ) : null}

      {view.status === 'submitted' ? (
        <ReportSection
          interviewId={view.id}
          actions={() => <CorrectionControl targetType="report" targetId={view.id} />}
        />
      ) : null}
      {view.status !== 'cancelled' || view.cancellationReason !== 'unavailable' ? (
        <div className="flex flex-wrap gap-3">
          <ReportControl
            targetType="brief"
            targetId={view.briefId}
            label="Report this brief or founder"
          />
          <BlockControl userId={view.founderUserId} name={view.founder.displayName} />
        </div>
      ) : null}

      <BriefPreviewCard preview={view.brief} />

      {can('withdraw_consent') ? (
        <Card as="section">
          <CardHeader
            title={
              <span className="flex items-center gap-2">
                <ShieldCheck className="size-4 text-ink-muted" aria-hidden="true" /> Your consent
              </span>
            }
            description={
              view.status === 'submitted'
                ? 'Withdrawing stops the founder’s access to your answers and report immediately.'
                : 'Withdrawing cancels this interview.'
            }
          />
          {view.consent ? (
            <p className="mb-3 text-sm text-ink-muted">
              Granted {formatDate(view.consent.grantedAt)} ·{' '}
              {view.consent.items.speech_transcription ? 'voice answers' : 'typed answers'} ·
              providers: {view.consent.disclosedProviders.join(', ')}
            </p>
          ) : null}
          <Button
            variant="secondary"
            loading={actions.withdraw.isPending}
            onClick={() => actions.withdraw.mutate()}
          >
            Withdraw consent
          </Button>
        </Card>
      ) : null}
      {view.brief.founder.demoAccount ? <Badge tone="caution">Demo data</Badge> : null}
    </div>
  );
}

export function CandidateInterviewPage() {
  const { interviewId = '' } = useParams();
  const query = useInterview(interviewId);
  return <QueryState query={query}>{(view) => <Body view={view} />}</QueryState>;
}
